-- Q29. Repeat vs One-Time Customers
-- Classify every customer who has placed at least one order
-- as:
--
-- 'One-Time Customer' → exactly 1 order
-- 'Repeat Customer'   → more than 1 order

select user_id as customer_id, count(id) as number_of_orders, 
