-- Q26. Customers Who Spent More Than Average
-- Find customers whose total spending is greater than
-- the average spending across all customers who placed
-- at least one order.

with total_spendings as (
select distinct user_id as customer_id, sum(total) over(partition by user_id) as order_amount
from order_details od),
avg_order as (
select customer_id, order_amount, avg(order_amount) over() as avg_order_amount
from total_spendings)
select distinct customer_id, order_amount
from avg_order 
where order_amount > avg_order_amount 
order by customer_id 

-- Q27. Running Revenue by Order Date
-- Show each order and the cumulative revenue generated
-- up to that order date.

select id as order_id, created_at as order_date, total as order_total, 
sum(total) over(order by created_at rows between unbounded preceding and current row) as running_revenue
from order_details od 
order by order_id

-- Q28. Previous Order Amount
