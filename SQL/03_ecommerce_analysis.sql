-- Q35. BEST-SELLING PRODUCTS
-- Find the top 5 products by quantity sold.
--   - product_id
--   - product name
--   - quantity sold
--   - revenue generated

select oi.product_id, p.name as product_name, sum(oi.quantity) as quantity_sold,
(p.price*sum(oi.quantity))*(1-coalesce(d.discount_percent,0)*0.01) as total_revenue_generated_after_discount
from order_details od 
join order_items oi 
on od.id = oi.order_id 
join product p 
on oi.product_id = p.id 
left join discount d 
on p.discount_id = d.id 
group by oi.product_id, p."name", p.price, d.discount_percent 
order by total_revenue_generated_after_discount desc
limit 5

-- Q36. CATEGORY PERFORMANCE
-- For each product category, show:
--   - category name
--   - number of products
--   - quantity sold
--   - total revenue

with product_category_details as (
select pc.id, pc.name, count(p.id) as number_of_products, coalesce(sum(oi.quantity), 0) as quantity_sold
from product_category pc 
left join product p 
on pc.id = p.category_id 
left join order_items oi 
on p.id = oi.product_id 
group by pc."name", pc.id),
product_revenue_details as (
select p.id, p.category_id, (p.price*sum(oi.quantity))*(1-coalesce(d.discount_percent,0)*0.01) as total_revenue_generated_after_discount
from product p 
left join discount d 
on p.discount_id = d.id
left join order_items oi 
on p.id = oi.product_id 
group by p.id, p.category_id, p.price, d.discount_percent)
select name as category_name, number_of_products, quantity_sold, coalesce(sum(total_revenue_generated_after_discount), 0) as total_revenue_generated_after_discount
from product_category_details pc
left join product_revenue_details pr
on pc.id = pr.category_id 
group by name, number_of_products, quantity_sold 
order by total_revenue_generated_after_discount desc 

