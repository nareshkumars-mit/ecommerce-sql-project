-- Q1. Registered Customers
-- How many customers are registered on the platform?

select count(id) as registered_customers
from "user" u 

-- Q2. Orders & Revenue
-- How many orders have been placed and what is the total revenue?

select count(id) as total_orders, sum(total) as total_revenue
from order_details od 

-- Q3. Average Order Value
-- What is the average order value?

select avg(total) as avg_order_value
from order_details od 

-- Q4. Highest & Lowest Order
-- What are the highest and lowest order values?

select max(total) as highest_order_amount, min(total) as lowest_order_amount
from order_details od 

-- Q5. Total Products
-- How many products are available in the product table?

select count(id) as total_available_products
from product p 

-- Q6. Total Product Categories
-- How many product categories exist?

select count(id) as total_available_product_categories
from product_category pc 

-- Q7. Total Shopping Sessions
-- How many shopping sessions have been created?

select count(id) as total_shopping_session
from shopping_session ss 

-- Q8. Cart Items & Total Units
-- How many cart-item records do we have,
-- and how many total product units are represented by them?

select count(id) as total_cart_items, sum(quantity) as total_units_in_cart
from cart_item ci 

-- Q9. Successful Payments
-- How many total payments are there,
-- and how many have Completed status?

select count(id) as total_payments, count(case when status = 'Completed' then id end) as completed_payments
from payment_details pd 

-- Q10. Payment Status Breakdown
-- How many payments are there for each payment status?

select status as payment_status, count(id) as count
from payment_details pd 
group by pd.status 

-- Q11. Revenue by Payment Status
-- How much payment amount is associated with each payment status?

select status as payment_status, sum(amount) as total_revenue
from payment_details pd 
group by pd.status 

-- Q12. Orders by Customer
-- Show each customer and the number of orders they have placed.
-- Include customers who have ZERO orders.

select u.id as customer_id, count(od.id) as number_of_orders
from "user" u 
left join order_details od 
on u.id = od.user_id 
group by u.id 
order by customer_id 

-- Q13. Revenue by Customer
-- Show each customer and their total spending.
-- Only customers who have placed orders need to appear.

select u.id as customer_id, sum(od.total) as total_spending
from "user" u 
join order_details od 
on u.id = od.user_id 
group by u.id 
order by u.id 

-- Q14. Products by Category
-- Show each product category and the number of products
-- belonging to that category.

select pc.name as product_category_name, count(p.id) as total_products
from product_category pc 
join product p 
on pc.id = p.category_id 
group by pc."name" 
order by product_category_name 

-- Q15. Average Product Price by Category
-- What is the average product price for each category?

select pc.name as product_category_name, avg(price) as avg_product_category_price
from product_category pc 
join product p 
on pc.id = p.category_id 
group by pc."name" 
order by product_category_name 

-- Q16. Orders Above Average
-- Find all orders whose total is greater than the
-- overall average order value.

with avg_order as (
select id as order_id, user_id, total as order_amount, avg(total) over() as avg_order_amount
from order_details od)
select order_id, user_id, order_amount
from avg_order 
where order_amount > avg_order_amount 

-- Q17. Customers With More Than One Order
-- Find customers who have placed more than one order.

select user_id as customer_id, count(id) as orders
from order_details od 
group by od.user_id 
having count(id)>1

-- Q18. Revenue by Product
-- Calculate the revenue generated by each product.

select oi.product_id, p.name as product_name, sum(((oi.quantity*p.price)*(1-(coalesce(d.discount_percent,0)/100)))) as revenue
from order_items oi 
join product p 
on oi.product_id = p.id 
left join discount d 
on p.discount_id = d.id 
group by oi.product_id, p."name" 
order by revenue desc 

-- Q19. Revenue by Category
-- Calculate the total revenue generated by each product category.

select p.category_id, pc.name, sum(((oi.quantity*p.price)*(1-(coalesce(d.discount_percent,0)/100)))) as revenue
from order_items oi 
join product p 
on oi.product_id = p.id 
join product_category pc 
on p.category_id = pc.id
left join discount d 
on p.discount_id = d.id 
group by p.category_id, pc.name
order by revenue desc 

-- Q20. Cart Conversion Rate
-- Calculate the percentage of shopping sessions
-- that resulted in an order.

select count(ss.id) as total_shopping_sessions, count(od.id) as total_orders, (count(od.id)*100.0)/count(ss.id) as conversion_rate
from shopping_session ss 
left join order_details od 
on ss.id = od.session_id 

-- Q21. Top Customers by Spending
-- Rank customers based on their total spending.

with spendings as (
select user_id as customer_id, sum(total) over(partition by user_id) as total_spendings
from order_details od),
ranked_spendings as (
select customer_id, total_spendings, dense_rank() over(order by total_spendings desc) as spendings_rank
from spendings)
select customer_id, total_spendings
from ranked_spendings 
where spendings_rank <=10

-- Q22. Top 3 Products by Revenue
-- Find the top 3 products based on revenue.
-- If products have the same revenue, they should receive
-- the same ranking.


-- Write your query below:

with product_revenue as (
select oi.product_id, p.name as product_name, sum(((oi.quantity*p.price)*(1-(coalesce(d.discount_percent,0)/100)))) as revenue,
dense_rank() over(order by sum(((oi.quantity*p.price)*(1-(coalesce(d.discount_percent,0)/100)))) desc) as revenue_rank
from order_items oi 
join product p 
on oi.product_id = p.id 
left join discount d 
on p.discount_id = d.id 
group by oi.product_id, p."name" 
order by revenue desc)
select product_id, product_name, revenue
from product_revenue 
where revenue_rank <=3

-- Q23. Highest-Revenue Product in Each Category
-- Find the highest-revenue product within every category.

with o1 as (
select distinct pc.name as category_name, p.name as product_name,
sum(((oi.quantity*p.price)*(1-(coalesce(d.discount_percent,0)/100)))) as product_revenue,
dense_rank() over(partition by pc.name order by sum(((oi.quantity*p.price)*(1-(coalesce(d.discount_percent,0)/100)))) desc) as revenue_rank
from order_items oi 
join product p 
on oi.product_id = p.id 
join product_category pc 
on p.category_id = pc.id
left join discount d 
on p.discount_id = d.id 
group by pc.name, p.name)
select category_name, product_name, product_revenue
from o1
where revenue_rank = 1
order by o1.product_revenue desc 

-- Q24. Customer Order Ranking
