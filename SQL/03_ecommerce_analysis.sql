-- Q41. INACTIVE CUSTOMERS
-- Find customers who have placed at least one order but
-- have NOT placed an order in the most recent 30 days
-- relative to the latest order date in the database.

with calculated as (
select distinct user_id as customer_id, max(to_char(created_at, 'YYYY-MM-DD')) over(partition by user_id) as latest_order_date_of_customer,
max(to_char(created_at, 'YYYY-MM-DD')) over() as lastest_order_date_at_store
from order_details od)
select customer_id, latest_order_date_of_customer
from calculated 
where to_date(lastest_order_date_at_store, 'YYYY-MM-DD') - to_date(latest_order_date_of_customer, 'YYYY-MM-DD') > 30
order by latest_order_date_of_customer desc 

